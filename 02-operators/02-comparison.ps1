$a = 10
$b = 5

# Equal
$a -eq $b
# False

# Not equal
$a -ne $b
# True

# Greater than
$a -gt $b
# True

# Less than
$a -lt $b
# False

# Greater than or equal
$a -ge $b
# True

# Less than or equal
$a -le $b
# False


<#
PowerShell comparison operators:

-eq → Equal

-ne → Not equal

-gt → Greater than

-lt → Less than

-ge → Greater than or equal

-le → Less than or equal
#>


