# Addition
$a = 10
$b = 5
$result = $a + $b
Write-Host $result       # 15

# Subtraction
$result = $a - $b
Write-Host $result       # 5

# Multiplication
$result = $a * $b
Write-Host $result       # 50

# Division
$result = $a / $b
Write-Host $result       # 2

# Modulus (remainder)
$result = $a % $b
Write-Host $result       # 0

# Power
$result = ($a ** 2)
Write-Host $result       # 100


<#
Common arithmetic operators:

+ → Add

- → Subtract

* → Multiply

/ → Divide

% → Remainder

** → Power

#>